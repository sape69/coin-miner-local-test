"use strict";


// ============================================================
// 🐱 STELLA FIREBASE
// ============================================================
//
// Vastaa:
//
// 🔥 Firebase Admin SDK:n alustuksesta
// 📦 Firestore-yhteydestä
// 👤 User-documenttien referenceista
// 📜 Transaction History -referenceista
// 📺 AdMob Reward -referenceista
//
// ============================================================


// ============================================================
// FIREBASE ADMIN APP
// ============================================================

const {
  initializeApp,
  getApps,
} = require(
  "firebase-admin/app"
);


// ============================================================
// FIRESTORE
// ============================================================

const {
  getFirestore,
  FieldValue,
} = require(
  "firebase-admin/firestore"
);


// ============================================================
// 🐱 INITIALIZE FIREBASE
// ============================================================
//
// Firebase alustetaan vain kerran.
//
// Tämä estää virheen:
//
// "The default Firebase app already exists"
//
// ============================================================

if (
  getApps().length === 0
) {

  initializeApp();

}


// ============================================================
// 🔥 FIRESTORE DATABASE
// ============================================================

const db =
  getFirestore();


// ============================================================
// 👤 USER DOCUMENT
// ============================================================
//
// Polku:
//
// users/{uid}
//
// ============================================================

function getUserRef(uid) {

  return db
    .collection("users")
    .doc(uid);

}


// ============================================================
// 📜 USER TRANSACTION HISTORY
// ============================================================
//
// Polku:
//
// users/{uid}/transactions/{transactionId}
//
// ============================================================

function getHistoryCollection(uid) {

  return getUserRef(uid)
    .collection("transactions");

}


// ============================================================
// 📺 ADMOB REWARD
// ============================================================
//
// Polku:
//
// admobRewards/{transactionId}
//
// ============================================================

function getAdMobRewardRef(
  transactionId
) {

  return db
    .collection("admobRewards")
    .doc(transactionId);

}


// ============================================================
// 📦 EXPORTS
// ============================================================

module.exports = {

  // ----------------------------------------------------------
  // 🔥 FIRESTORE
  // ----------------------------------------------------------

  db,


  // ----------------------------------------------------------
  // ⏱️ FIRESTORE FIELD VALUES
  // ----------------------------------------------------------

  FieldValue,


  // ----------------------------------------------------------
  // 👤 USER
  // ----------------------------------------------------------

  getUserRef,


  // ----------------------------------------------------------
  // 📜 HISTORY
  // ----------------------------------------------------------

  getHistoryCollection,


  // ----------------------------------------------------------
  // 📺 ADMOB
  // ----------------------------------------------------------

  getAdMobRewardRef,

};