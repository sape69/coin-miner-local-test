  static String getDailyFact({
    required String languageCode,
    DateTime? date,
  }) {
    final DateTime inputDate = (date ?? DateTime.now()).toUtc();

    final DateTime utcDay = DateTime.utc(
      inputDate.year,
      inputDate.month,
      inputDate.day,
    );

    final DateTime startDay = DateTime.utc(
      2026,
      1,
      1,
    );

    final int dayIndex = utcDay.difference(startDay).inDays;

    final List<String> facts = _factsForLanguage(languageCode);

    if (facts.isEmpty) {
      return '';
    }

    final int index =
        ((dayIndex % facts.length) + facts.length) % facts.length;

    return facts[index];
  }

  // ==========================================================
  // 🌍 LANGUAGE SELECTION
  // ==========================================================

  static List<String> _factsForLanguage(
    String languageCode,
  ) {
    final String normalizedCode =
        languageCode.trim().toLowerCase().split('-').first;

    switch (normalizedCode) {
      case 'fi':
        return fi;
      case 'en':
        return en;
      case 'de':
        return de;
      case 'es':
        return es;
      case 'fr':
        return fr;
      case 'zh':
        return zh;
      case 'vi':
        return vi;
      case 'ja':
        return ja;
      default:
        return en;
    }
  }
