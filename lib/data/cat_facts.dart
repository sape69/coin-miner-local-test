  static String getDailyFact({
    required String languageCode,
    DateTime? date,
  }) {
    final selectedDate = date ?? DateTime.now();

    final utcDate = DateTime.utc(
      selectedDate.year,
      selectedDate.month,
      selectedDate.day,
    );

    final startDate = DateTime.utc(2026, 1, 1);

    final dayIndex = utcDate.difference(startDate).inDays;

    final facts = _factsForLanguage(languageCode);

    if (facts.isEmpty) {
      return en.first;
    }

    final safeDayIndex = dayIndex < 0 ? 0 : dayIndex;

    // 37 ja 150 ovat keskenään suhteellisia alkulukuja.
    // Näin kaikki 150 faktaa käydään läpi ennen kuin kierros alkaa alusta.
    final index = (safeDayIndex * 37 + 17) % facts.length;

    return facts[index];
  }

  // ============================================================
  // LANGUAGE SELECTION
  // ============================================================

  static List<String> _factsForLanguage(String languageCode) {
    final normalizedCode = languageCode
        .trim()
        .toLowerCase()
        .split('-')
        .first;

    switch (normalizedCode) {
      case 'fi':
        return fi;
      case 'en':
        return en;
      case 'de':
        return de;
      case 'es':
        return es;
      case 'fr':
        return fr;
      case 'zh':
        return zh;
      case 'vi':
        return vi;
      case 'ja':
        return ja;
      default:
        return en;
    }
  }
