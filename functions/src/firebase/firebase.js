"use strict";

// ============================================================
// 🐱 STELLA FIREBASE
// ============================================================
//
// Vastaa:
//
// 🔥 Firebase Admin SDK:n alustuksesta
// 📦 Firestore-yhteydestä
// ⏱️ Firestore FieldValue -työkalusta
// 🔐 Firebase Authentication -yhteydestä
//
// ============================================================


// ============================================================
// 🔥 FIREBASE ADMIN APP
// ============================================================

const {
  initializeApp,
  getApps,
} = require(
  "firebase-admin/app",
);


// ============================================================
// 🔐 FIREBASE AUTHENTICATION
// ============================================================

const {
  getAuth,
} = require(
  "firebase-admin/auth",
);


// ============================================================
// 📦 FIRESTORE
// ============================================================

const {
  getFirestore,
  FieldValue,
} = require(
  "firebase-admin/firestore",
);


// ============================================================
// 🚀 INITIALIZE FIREBASE
// ============================================================
//
// Firebase Admin alustetaan vain kerran.
//
// Tämä estää virheen:
//
// "The default Firebase app already exists"
//
// ============================================================

if (
  getApps().length === 0
) {
  initializeApp();
}


// ============================================================
// 🔥 FIRESTORE DATABASE
// ============================================================

const db =
  getFirestore();


// ============================================================
// 🔐 FIREBASE AUTH
// ============================================================

const auth =
  getAuth();


// ============================================================
// 📦 EXPORTS
// ============================================================

module.exports = {

  // ----------------------------------------------------------
  // 🔥 FIRESTORE DATABASE
  // ----------------------------------------------------------

  db,


  // ----------------------------------------------------------
  // 🔐 FIREBASE AUTHENTICATION
  // ----------------------------------------------------------

  auth,


  // ----------------------------------------------------------
  // ⏱️ FIRESTORE FIELD VALUES
  // ----------------------------------------------------------

  FieldValue,

};